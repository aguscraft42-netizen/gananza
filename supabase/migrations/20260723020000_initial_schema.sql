-- Gananza V5 - initial secure schema
create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;
grant usage on schema private to authenticated, service_role;

create type public.app_role as enum ('user', 'support', 'reviewer', 'admin');
create type public.offer_category as enum ('game', 'survey', 'app', 'service');
create type public.offer_status as enum ('draft', 'active', 'paused', 'ended');
create type public.task_session_status as enum ('opened', 'started', 'registered', 'pending', 'confirmed', 'rejected', 'reversed', 'expired');
create type public.conversion_status as enum ('pending', 'confirmed', 'rejected', 'reversed');
create type public.withdrawal_status as enum ('requested', 'reviewing', 'approved', 'paid', 'rejected', 'cancelled');
create type public.payout_method_type as enum ('mercado_pago', 'bank_transfer');
create type public.ticket_status as enum ('open', 'waiting_user', 'waiting_team', 'resolved', 'closed');
create type public.ticket_priority as enum ('low', 'normal', 'high', 'urgent');
create type public.fraud_flag_status as enum ('open', 'reviewing', 'resolved', 'dismissed');
