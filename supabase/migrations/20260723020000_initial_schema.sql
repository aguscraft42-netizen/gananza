create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  country_code text not null default 'AR' check (char_length(country_code) = 2),
  birth_date date,
  interests text[] not null default '{}',
  payout_preference public.payout_method_type not null default 'mercado_pago',
  onboarding_completed_at timestamptz,
  risk_score integer not null default 0 check (risk_score between 0 and 100),
  level integer not null default 1 check (level >= 1),
  experience_points integer not null default 0 check (experience_points >= 0),
  streak_days integer not null default 0 check (streak_days >= 0),
  hide_balance boolean not null default false,
  notification_preferences jsonb not null default '{"tasks":true,"withdrawals":true,"support":true}'::jsonb,
  suspended_at timestamptz,
  suspension_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.user_roles (
